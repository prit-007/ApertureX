import 'dart:io';

/// Generates an Inno Setup (.iss) script for ApertureX and optionally compiles
/// it with ISCC into a Windows installer (.exe).
///
/// Runs with CWD=app/ (e.g. `dart run tool/build_installer.dart`). Paths are
/// resolved absolutely so the script works regardless of the caller's CWD.
///
/// Modes:
///   `--dry-run`      Generate aperturex_setup_`<ver>`.iss without ISCC (CI-safe,
///                  runs on Ubuntu). Default when `--iscc` is absent.
///   `--iscc <path>`  Also compile the .iss with ISCC at `<path>` to produce the
///                  .exe installer.
///
/// The script asserts that the required inputs (LICENSE, pubspec.yaml,
/// app_icon.ico) exist and fails loudly if any is missing. In --dry-run mode,
/// the Release dir and engine DLL are not required (they only exist after a
/// Windows build).
void main(List<String> args) {
  final isDryRun = args.contains('--dry-run');
  final isccIdx = args.indexOf('--iscc');
  final isccPath = isccIdx >= 0 && isccIdx + 1 < args.length
      ? args[isccIdx + 1]
      : null;

  final appDir = Directory.current;
  final repoDir = Directory('${appDir.path}/..').absolute;

  // --- Version from pubspec.yaml ------------------------------------------
  final pubspec = File('${appDir.path}/pubspec.yaml');
  if (!pubspec.existsSync()) {
    stderr.writeln('ERROR: pubspec.yaml not found at ${pubspec.path}');
    exit(1);
  }
  final versionLine = pubspec.readAsLinesSync().firstWhere(
        (l) => l.startsWith('version:'),
        orElse: () => '',
      );
  final versionMatch = RegExp(r'version:\s*([0-9]+\.[0-9]+\.[0-9]+)').firstMatch(versionLine);
  if (versionMatch == null) {
    stderr.writeln('ERROR: could not parse version from pubspec.yaml: $versionLine');
    exit(1);
  }
  final appVersion = versionMatch.group(1)!;

  // --- Inputs that must exist --------------------------------------------
  final licenseFile = File('${repoDir.path}/LICENSE').absolute;
  if (!licenseFile.existsSync()) {
    stderr.writeln('ERROR: LICENSE not found at ${licenseFile.path}');
    exit(1);
  }

  final iconFile = File(
    '${appDir.path}/windows/runner/resources/app_icon.ico',
  ).absolute;
  if (!iconFile.existsSync()) {
    stderr.writeln('ERROR: app_icon.ico not found at ${iconFile.path}');
    exit(1);
  }

  // --- Output paths --------------------------------------------------------
  final installersDir = Directory('${appDir.path}/build/installers').absolute
    ..createSync(recursive: true);
  final issPath = File(
    '${installersDir.path}/aperturex_setup_$appVersion.iss',
  ).absolute;

  // Fresh AppId GUID for ApertureX (do not reuse nook's — separate products
  // must not collide in Windows' uninstall registry).
  const appId = '4F3A8C2E-7B1D-4A9F-8C3D-2E1F4A6B8C9D';

  // --- Generate .iss -------------------------------------------------------
  // The Release dir is only referenced inside the .iss [Files] section as a
  // literal path; it does not need to exist at .iss-generation time.
  final releaseDir = Directory('${appDir.path}/build/windows/x64/runner/Release')
      .absolute;

  final iss = '''
; ApertureX Inno Setup script
; Generated by tool/build_installer.dart — do not edit by hand.
; CWD: ${appDir.path}

[Setup]
AppName=ApertureX
AppVersion=$appVersion
AppId={{$appId}}
AppPublisher=ApertureX Contributors
AppPublisherURL=https://github.com/prit-007/ApertureX
AppSupportURL=https://github.com/prit-007/ApertureX/issues
AppUpdatesURL=https://github.com/prit-007/ApertureX/releases
DefaultDirName={localappdata}\\\\aperturex
DefaultGroupName=ApertureX
AllowNoIcons=yes
LicenseFile=${licenseFile.absolute.path}
WizardStyle=modern
PrivilegesRequired=lowest
ArchitecturesInstallIn64BitMode=x64compatible
Compression=lzma2
SolidCompression=yes
ChangesEnvironment=yes
CloseApplications=yes
SetupIconFile=${iconFile.absolute.path}
OutputDir=${installersDir.absolute.path}
OutputBaseFilename=aperturex_setup_$appVersion

[Languages]
Name: "english"; MessagesFile: "compiler:Default.isl"

[Tasks]
Name: "desktopicon"; Description: "Create a &desktop icon"; GroupDescription: "Additional icons:"; Flags: unchecked

[Files]
Source: "${releaseDir.absolute.path}\\\\*"; DestDir: "{app}"; Flags: recursesubdirs createallsubdirs

[Icons]
Name: "{group}\\\\ApertureX"; Filename: "{app}\\\\aperturex.exe"
Name: "{commondesktop}\\\\ApertureX"; Filename: "{app}\\\\aperturex.exe"; Tasks: desktopicon

[Run]
Filename: "{app}\\\\aperturex.exe"; Description: "Launch ApertureX"; Flags: nowait postinstall skipifsilent
''';

  issPath.writeAsStringSync(iss);
  print('Generated ${issPath.path}');
  print('  AppId: $appId');
  print('  Version: $appVersion');
  print('  License: ${licenseFile.absolute.path}');
  print('  Icon: ${iconFile.absolute.path}');
  print('  Release dir (in .iss): ${releaseDir.absolute.path}');

  if (!isDryRun && isccPath == null) {
    print('Dry-run mode: .iss generated, not compiled (pass --iscc to compile).');
  }

  // --- Compile with ISCC if requested -------------------------------------
  if (isccPath != null) {
    // In compile mode, the Release dir and engine DLL are required.
    if (!releaseDir.existsSync()) {
      stderr.writeln('ERROR: Release dir not found at ${releaseDir.path}');
      stderr.writeln('Run "flutter build windows --release" first.');
      exit(1);
    }
    final engineDll = File('${releaseDir.path}/rust_lib_aperturex.dll');
    if (!engineDll.existsSync()) {
      stderr.writeln(
          'ERROR: rust_lib_aperturex.dll not found in ${releaseDir.path}');
      exit(1);
    }
    if (engineDll.lengthSync() == 0) {
      stderr.writeln('ERROR: rust_lib_aperturex.dll is empty');
      exit(1);
    }

    final iscc = File(isccPath);
    if (!iscc.existsSync()) {
      stderr.writeln('ERROR: ISCC not found at ${iscc.absolute.path}');
      exit(1);
    }
    final result = Process.runSync(
      iscc.absolute.path,
      [issPath.absolute.path],
      workingDirectory: appDir.path,
    );
    if (result.exitCode != 0) {
      stderr.writeln('ISCC failed (exit ${result.exitCode}):');
      stderr.writeln(result.stdout);
      stderr.writeln(result.stderr);
      exit(1);
    }
    final exePath = File(
      '${installersDir.path}/aperturex_setup_$appVersion.exe',
    );
    if (!exePath.existsSync()) {
      stderr.writeln('ERROR: ${exePath.path} was not produced by ISCC');
      exit(1);
    }
    print('Built ${exePath.path} (${exePath.lengthSync()} bytes)');
  }
}

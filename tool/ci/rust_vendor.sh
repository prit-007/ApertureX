#!/usr/bin/env bash
# Vendor the Rust crate graph for OFFLINE builds (the F-Droid builder has no
# network; crates.io is unreachable there). Regenerating and committing
# app/rust/vendor + app/rust/.cargo makes `cargo build` work with zero network.
#
# Usage:
#   tool/ci/rust_vendor.sh            regenerate the vendor dir + cargo config
#   tool/ci/rust_vendor.sh --check    verify vendor matches Cargo.lock (gates
#                                     the F-Droid build; use in Prebuild)
#
# Note: the F-Droid submission commits these dirs (git add -f — they are
# gitignored by default so everyday CI keeps building against crates.io).
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/../.."

RUST_DIR=app/rust
VENDOR=$RUST_DIR/vendor
STAMP=$VENDOR/.cargo-lock-sha256
CONFIG=$RUST_DIR/.cargo/config.toml

lock_hash() { sha256sum "$RUST_DIR/Cargo.lock" | cut -d' ' -f1; }

if [ "${1:-}" = "--check" ]; then
  [ -f "$STAMP" ] || {
    echo "Vendored crates missing — run tool/ci/rust_vendor.sh and commit" \
      "app/rust/vendor + app/rust/.cargo for the F-Droid build." >&2
    exit 1
  }
  if [ "$(cat "$STAMP")" != "$(lock_hash)" ]; then
    echo "Vendored crates are stale vs app/rust/Cargo.lock — re-run" \
      "tool/ci/rust_vendor.sh and commit the result." >&2
    exit 1
  fi
  [ -f "$CONFIG" ] || {
    echo "Missing $CONFIG (required for offline builds)." >&2
    exit 1
  }
  echo "Vendored crates OK (matches Cargo.lock)."
  exit 0
fi

mkdir -p "$VENDOR"
(cd "$RUST_DIR" && cargo vendor --versioned-dirs vendor > /dev/null)

mkdir -p "$RUST_DIR/.cargo"
cat > "$CONFIG" <<'EOF'
# Generated by tool/ci/rust_vendor.sh — offline source replacement so the
# F-Droid builder (no network) resolves crates from ./vendor instead of
# crates.io. Regenerate after every Cargo.lock change.
[source.crates-io]
replace-with = "vendored-sources"

[source.vendored-sources]
directory = "vendor"
EOF

printf '%s' "$(lock_hash)" > "$STAMP"
echo "Vendored to $VENDOR (offline cargo config at $CONFIG)."
echo "Commit both for the F-Droid build: git add -f app/rust/vendor app/rust/.cargo"
